import urllib.request

SERVICE_NAME = "Demo Internal App"
HEALTH_URL = "http://127.0.0.1:9000/health"


def check_service_health(timeout: float = 3.0) -> dict:
    """Probe the demo service's /health endpoint. Read-only, changes nothing."""
    try:
        with urllib.request.urlopen(HEALTH_URL, timeout=timeout) as resp:
            if resp.status == 200:
                return {"service": SERVICE_NAME, "healthy": True, "detail": "HTTP 200"}
            return {"service": SERVICE_NAME, "healthy": False, "detail": f"HTTP {resp.status}"}
    except Exception as e:
        return {"service": SERVICE_NAME, "healthy": False, "detail": f"{type(e).__name__}: {e}"}

import subprocess
import sys
import time
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent

# Allowlist: the only actions the agent can ever run.
# Fixed commands written by us, never generated by an LLM.
ALLOWED_ACTIONS = {
    "restart_demo_service": [
        sys.executable, "-m", "uvicorn", "test_service.demo_app:app", "--port", "9000",
    ],
}


def execute_action(action_id: str) -> dict:
    """Run an allowlisted recovery action. Anything else is refused."""
    if action_id not in ALLOWED_ACTIONS:
        return {"action": action_id, "executed": False, "detail": "Action not in allowlist"}
    try:
        flags = 0
        if sys.platform == "win32":
            flags = subprocess.CREATE_NEW_PROCESS_GROUP | subprocess.CREATE_NO_WINDOW
        subprocess.Popen(
            ALLOWED_ACTIONS[action_id],
            cwd=PROJECT_ROOT,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            creationflags=flags,
        )
        return {"action": action_id, "executed": True, "detail": "Process launched"}
    except Exception as e:
        return {"action": action_id, "executed": False, "detail": f"{type(e).__name__}: {e}"}


def verify_recovery(timeout: float = 15.0, interval: float = 1.0) -> dict:
    """Poll /health until it responds or the timeout passes. Success only if it really responds."""
    deadline = time.time() + timeout
    result = check_service_health(timeout=2.0)
    while not result["healthy"] and time.time() < deadline:
        time.sleep(interval)
        result = check_service_health(timeout=2.0)
    return {**result, "recovered": result["healthy"]}

import json
from datetime import datetime

LOG_PATH = PROJECT_ROOT / "backend" / "logs" / "recovery_actions.log"

RECOVERY_KEYWORDS = [
    "application", "app ", "service", "not responding", "unavailable",
    "down", "outage", "cannot access", "can't access", "not working", "crashed",
]


def should_run(text: str) -> bool:
    t = text.lower()
    return any(k in t for k in RECOVERY_KEYWORDS)


def log_incident(entry: dict) -> None:
    """Append one JSON line per recovery event."""
    LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    entry = {"time": datetime.now().isoformat(timespec="seconds"), **entry}
    with open(LOG_PATH, "a", encoding="utf-8") as f:
        f.write(json.dumps(entry) + "\n")


def propose_recovery(text: str) -> dict:
    """Detect and propose only. Nothing is changed until a human approves."""
    if not should_run(text):
        return {"triggered": False}
    health = check_service_health()
    if health["healthy"]:
        return {"triggered": True, "problem_detected": False, "health": health}
    proposal = {
        "triggered": True,
        "problem_detected": True,
        "health": health,
        "proposed_action": "restart_demo_service",
        "description": "Restart the Demo Internal App on port 9000",
        "requires_approval": True,
    }
    log_incident({"event": "proposed", "action": proposal["proposed_action"], "detail": health["detail"]})
    return proposal


def run_recovery(action_id: str) -> dict:
    """Called only after human approval: execute, verify, log, escalate on failure."""
    log_incident({"event": "approved", "action": action_id})
    executed = execute_action(action_id)
    if not executed["executed"]:
        outcome = {"action": action_id, "recovered": False, "escalate": True, "detail": executed["detail"]}
    else:
        verified = verify_recovery()
        outcome = {
            "action": action_id,
            "recovered": verified["recovered"],
            "escalate": not verified["recovered"],
            "detail": verified["detail"],
        }
    log_incident({"event": "outcome", **outcome})
    return outcome